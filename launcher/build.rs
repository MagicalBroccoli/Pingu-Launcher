use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

/// Files of the pingu-policy DKMS package.
const MODULE_FILES: [&str; 8] = [
    "Makefile",
    "dkms.conf",
    "probe.c",
    "policy.c",
    "policy.h",
    "trampoline.S",
    "README.md",
    "validation",
];
const MODULE_DIRS: [&str; 1] = ["modules-load.d"];
/// Files of the cpuid_fault_emulation DKMS package.
const CPUID_FILES: [&str; 5] = ["Makefile", "dkms.conf", "README.md", "inc", "src"];
const LOCKS: [&str; 3] = ["nvidia", "amd", "intel"];

fn main() {
    let config = slint_build::CompilerConfiguration::new().with_style("fluent-dark".to_string());
    slint_build::compile_with_config("ui/main.slint", config).expect("compiling main.slint");

    let manifest = PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let out = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR"));
    let root = manifest.parent().expect("repository root").to_path_buf();

    let hook = hook_library(&root, &out);
    let mut source = String::new();
    let _ = writeln!(
        source,
        "pub static HOOK: &[u8] = include_bytes!({:?});",
        hook.display().to_string()
    );

    source.push_str("pub static MODULE_FILES: &[Asset] = &[\n");
    let module = root.join("pingu-policy");
    for name in MODULE_FILES {
        add_tree(&mut source, &module, Path::new(name));
    }
    for name in MODULE_DIRS {
        add_tree(&mut source, &module, Path::new(name));
    }
    source.push_str("];\n");

    source.push_str("pub static CPUID_MODULE_FILES: &[Asset] = &[\n");
    let cpuid_module = root.join("cpuid-fault");
    for name in CPUID_FILES {
        add_tree(&mut source, &cpuid_module, Path::new(name));
    }
    source.push_str("];\n");

    source.push_str("pub static LOCKS: &[(&str, &[u8])] = &[\n");
    for gpu in LOCKS {
        let path = root.join("runtime").join(format!("{gpu}.lock.json"));
        println!("cargo:rerun-if-changed={}", path.display());
        let _ = writeln!(
            source,
            "    ({gpu:?}, include_bytes!({:?})),",
            path.display().to_string()
        );
    }
    source.push_str("];\n");

    // The SteamOS loader is always embedded; the prebuilt modules only when a release build asks for them.
    source.push_str("pub static STEAMOS_LOADER: &[Asset] = &[\n");
    for name in ["pingu-modules-load", "pingu-modules.service"] {
        add_tree(&mut source, &root.join("steamos"), Path::new(name));
    }
    source.push_str("];\n");
    source.push_str("pub static STEAMOS_MODULES: &[Asset] = &[\n");
    if let Some(directory) = env::var_os("PINGU_STEAMOS_DIR") {
        add_steamos_builds(&mut source, Path::new(&directory));
    }
    source.push_str("];\n");

    // The helper programs are the binaries the VM gate has validated.
    for (name, constant) in [
        ("avx2-run-static", "AVX2_RUN"),
        ("xstate-probe-static", "XSTATE_PROBE"),
        ("policy-test-static", "POLICY_TEST"),
    ] {
        let path = module.join("validation").join(name);
        require(&path);
        let _ = writeln!(
            source,
            "pub static {constant}: &[u8] = include_bytes!({:?});",
            path.display().to_string()
        );
    }

    fs::write(out.join("assets.rs"), source).expect("writing assets.rs");
    println!("cargo:rerun-if-env-changed=PINGU_HOOK_SO");
    println!("cargo:rerun-if-env-changed=PINGU_HOOK_RUSTFLAGS");
    println!("cargo:rerun-if-env-changed=PINGU_STEAMOS_DIR");
    println!("cargo:rerun-if-changed=build.rs");
}

fn require(path: &Path) {
    if !path.is_file() {
        panic!(
            "{} is missing. It is generated by `make module-validation-assets`; `make launcher` runs that first.",
            path.display()
        );
    }
}

/// Adds the builds that `make steamos-modules` wrote: one directory per kernel build ID.
fn add_steamos_builds(source: &mut String, directory: &Path) {
    println!("cargo:rerun-if-changed={}", directory.display());
    let mut builds: Vec<_> = fs::read_dir(directory)
        .unwrap_or_else(|error| panic!("reading {}: {error}", directory.display()))
        .map(|entry| entry.expect("directory entry").file_name())
        .collect();
    builds.sort();
    for build in builds {
        for name in [
            "pingu_policy.ko",
            "cpuid_fault_emulation.ko",
            "SHA256SUMS",
            "source.json",
        ] {
            add_tree(source, directory, &Path::new(&build).join(name));
        }
    }
}

/// Adds `relative` (a file or a directory) below `base` to the asset table.
fn add_tree(source: &mut String, base: &Path, relative: &Path) {
    let path = base.join(relative);
    println!("cargo:rerun-if-changed={}", path.display());
    if path.is_dir() {
        let mut names: Vec<_> = fs::read_dir(&path)
            .unwrap_or_else(|error| panic!("reading {}: {error}", path.display()))
            .map(|entry| entry.expect("directory entry").file_name())
            .collect();
        names.sort();
        for name in names {
            add_tree(source, base, &relative.join(name));
        }
        return;
    }
    require(&path);
    let executable = {
        use std::os::unix::fs::PermissionsExt;
        fs::metadata(&path).expect("metadata").permissions().mode() & 0o111 != 0
    };
    let _ = writeln!(
        source,
        "    Asset {{ path: {:?}, mode: {}, data: include_bytes!({:?}) }},",
        relative.display().to_string(),
        if executable { "0o755" } else { "0o644" },
        path.display().to_string()
    );
}

/// The preload library: a prebuilt one from `PINGU_HOOK_SO`, otherwise built from `pingu-hook`.
fn hook_library(root: &Path, out: &Path) -> PathBuf {
    if let Some(prebuilt) = env::var_os("PINGU_HOOK_SO") {
        let prebuilt = PathBuf::from(prebuilt);
        println!("cargo:rerun-if-changed={}", prebuilt.display());
        require(&prebuilt);
        return prebuilt;
    }
    let source = root.join("pingu-hook");
    for name in ["Cargo.toml", "Cargo.lock", "protocol", "runtime", "xtask"] {
        println!("cargo:rerun-if-changed={}", source.join(name).display());
    }
    let library = out.join("pingu-hook.so");
    let mut flags = vec!["-Ctarget-cpu=x86-64".to_string()];
    if let Some(extra) = env::var_os("PINGU_HOOK_RUSTFLAGS") {
        flags.extend(extra.to_string_lossy().split_whitespace().map(String::from));
    }
    let cargo = env::var_os("CARGO").unwrap_or_else(|| "cargo".into());
    let mut command = Command::new(cargo);
    command
        .current_dir(&source)
        .args(["run", "--locked", "--quiet", "--package", "xtask", "--"])
        .args(["build", "--output"])
        .arg(&library)
        .env("CARGO_TARGET_DIR", out.join("hook-target"))
        // The hook runs inside the restricted process, so it must stay baseline x86-64.
        .env("CARGO_ENCODED_RUSTFLAGS", flags.join("\x1f"));
    // Wrappers and flags of the outer build (clippy, RUSTFLAGS) must not leak into this one.
    for name in [
        "RUSTC_WORKSPACE_WRAPPER",
        "CLIPPY_ARGS",
        "CLIPPY_CONF_DIR",
        "RUSTFLAGS",
        "RUSTDOCFLAGS",
        "CARGO_BUILD_TARGET",
        "CARGO_MAKEFLAGS",
    ] {
        command.env_remove(name);
    }
    let output = command.output().unwrap_or_else(|error| {
        panic!("cannot run cargo to build pingu-hook: {error}");
    });
    if !output.status.success() {
        panic!(
            "building pingu-hook failed ({}):\n{}{}",
            output.status,
            String::from_utf8_lossy(&output.stdout),
            String::from_utf8_lossy(&output.stderr)
        );
    }
    library
}
